window.OMSC_ACCREDITATION_AREAS = accreditationAreas;
window.OMSC_AREA_ONE_CRITERIA = areaOneParameterLevels;
const query = new URLSearchParams(window.location.search);
const requestedArea = query.get("area")?.toUpperCase();
let selectedArea = Object.prototype.hasOwnProperty.call(accreditationAreas, requestedArea) ? requestedArea : "I";
let area = accreditationAreas[selectedArea];
const requestedParameter = query.get("parameter")?.toUpperCase();
let selectedParameter = area.parameters.find(([key]) => key === requestedParameter) || area.parameters[0];
let viewMode = query.get("view") === "criteria" || (!query.has("view") && query.has("parameter")) ? "criteria" : "areas";
let expandedArea = selectedArea;

const areaNavigation = document.querySelector("#area-navigation");

function updateAddress(replace = false, preserveCriterion = false) {
  const url = new URL(window.location.href);
  url.searchParams.set("area", selectedArea);
  url.searchParams.set("parameter", selectedParameter[0]);
  url.searchParams.set("view", viewMode);
  if (!preserveCriterion) url.searchParams.delete("criterion");
  window.history[replace ? "replaceState" : "pushState"]({}, "", url);
}

function renderSidebarView() {
  const isCriteriaView = viewMode === "criteria";
  document.querySelector("#area-selection-panel").hidden = isCriteriaView;
  document.querySelector("#area-criteria-navigation").hidden = !isCriteriaView;
  document.querySelector("#area-sidebar-label").textContent = selectedArea;
}

function renderAreaNavigation() {
  areaNavigation.replaceChildren();
  areaKeys.forEach((key, index) => {
    const currentArea = accreditationAreas[key];
    const item = document.createElement("div");
    item.className = "area-navigation-item";

    const trigger = document.createElement("button");
    trigger.className = "area-navigation-trigger";
    trigger.type = "button";
    trigger.dataset.area = key;
    trigger.setAttribute("aria-expanded", String(expandedArea === key));
    if (selectedArea === key) trigger.setAttribute("aria-current", "page");

    const number = document.createElement("span");
    number.className = "area-navigation-number";
    number.textContent = String(index + 1).padStart(2, "0");
    const label = document.createElement("span");
    label.className = "area-navigation-label";
    label.textContent = `Area ${key}`;
    const arrow = document.createElement("span");
    arrow.className = "area-navigation-arrow";
    arrow.setAttribute("aria-hidden", "true");
    arrow.textContent = "⌄";
    trigger.append(number, label, arrow);
    trigger.addEventListener("click", () => {
      if (selectedArea === key) {
        expandedArea = expandedArea === key ? "" : key;
        renderAreaNavigation();
        return;
      }
      selectedArea = key;
      area = accreditationAreas[key];
      selectedParameter = area.parameters[0];
      expandedArea = key;
      viewMode = "areas";
      updateAddress();
      renderPage();
    });

    const parameters = document.createElement("div");
    parameters.className = "area-parameter-menu";
    parameters.id = `area-${key}-parameters`;
    parameters.hidden = expandedArea !== key;
    trigger.setAttribute("aria-controls", parameters.id);
    currentArea.parameters.forEach((parameter) => {
      const [parameterKey, name] = parameter;
      const link = document.createElement("a");
      link.href = `area.html?area=${encodeURIComponent(key)}&parameter=${encodeURIComponent(parameterKey)}`;
      link.className = "area-parameter-link";
      link.dataset.parameter = parameterKey;
      link.textContent = name;
      if (selectedArea === key && selectedParameter[0] === parameterKey) {
        link.setAttribute("aria-current", "page");
      }
      link.addEventListener("click", (event) => {
        event.preventDefault();
        selectedArea = key;
        area = currentArea;
        selectedParameter = parameter;
        expandedArea = key;
        viewMode = "criteria";
        updateAddress();
        renderPage();
      });
      parameters.append(link);
    });

    item.append(trigger, parameters);
    areaNavigation.append(item);
  });
}

function renderPage() {
  const [parameterKey, parameterName, parameterFolderId] = selectedParameter;
  const areaFolderUrl = `https://drive.google.com/drive/folders/${encodeURIComponent(area.folderId)}`;

  document.title = `Area ${selectedArea} | OMSC Institutional Accreditation`;
  document.querySelector("#area-title").textContent = `Area ${selectedArea}`;
  document.querySelector("#area-breadcrumb").textContent = `Area ${selectedArea}`;
  document.querySelector("#area-sidebar-label").textContent = selectedArea;
  document.querySelector("#document-area-crumb").textContent = `Area ${selectedArea}`;
  document.querySelector("#document-parameter-crumb").textContent = parameterName;
  document.querySelector("#area-content-title").textContent = `Area ${selectedArea} · ${area.title}`;
  document.querySelector("#area-content-description").textContent = `${area.summary}. Choose a parameter from the area dropdown to review its source documents.`;
  document.querySelector("#area-description").textContent = `${area.title}. Select a parameter from the area list to browse its supporting materials.`;
  document.querySelector("#area-drive-link").href = areaFolderUrl;
  renderSidebarView();

  document.querySelectorAll("[data-area-link]").forEach((link) => {
    if (link.dataset.areaLink === selectedArea) {
      link.setAttribute("aria-current", "page");
      link.classList.add("is-current-area");
    } else {
      link.removeAttribute("aria-current");
      link.classList.remove("is-current-area");
    }
  });

  renderAreaNavigation();
  window.OMSC_AREA_SELECTION = { area: selectedArea, parameterKey, parameterName, parameterFolderId, viewMode };
  window.dispatchEvent(new CustomEvent("area-selection-change", { detail: window.OMSC_AREA_SELECTION }));
}

function loadLocation() {
  const url = new URL(window.location.href);
  const areaKey = url.searchParams.get("area")?.toUpperCase();
  selectedArea = Object.prototype.hasOwnProperty.call(accreditationAreas, areaKey) ? areaKey : "I";
  area = accreditationAreas[selectedArea];
  const parameterKey = url.searchParams.get("parameter")?.toUpperCase();
  selectedParameter = area.parameters.find(([key]) => key === parameterKey) || area.parameters[0];
  const requestedView = url.searchParams.get("view");
  viewMode = requestedView === "areas" || requestedView === "criteria"
    ? requestedView
    : url.searchParams.has("parameter") ? "criteria" : "areas";
  expandedArea = selectedArea;
  const preserveCriterion = url.searchParams.has("criterion")
    && viewMode === "criteria"
    && url.searchParams.get("area")?.toUpperCase() === selectedArea
    && url.searchParams.get("parameter")?.toUpperCase() === selectedParameter[0];
  if (
    url.searchParams.get("parameter") !== selectedParameter[0]
    || requestedView !== viewMode
    || (viewMode === "areas" && url.searchParams.has("criterion"))
  ) updateAddress(true, preserveCriterion);
  renderPage();
}

document.querySelector("#back-to-areas").addEventListener("click", () => {
  viewMode = "areas";
  updateAddress();
  renderPage();
});

window.addEventListener("popstate", loadLocation);
loadLocation();
